func main() {
	os.Exit(Main(os.Args[1:], os.Stdout, os.Stderr))
}

// Main dispatches subcommands and returns the exit code.
func Main(args []string, stdout, stderr io.Writer) int {
	if len(args) == 0 {
		fmt.Fprintln(stderr, "usage: inspection-assessment plan|fixtures|origin|run|verify|summarize|calibrate [flags]")
		return 2
	}
	var err error
	switch args[0] {
	case "plan":
		err = planCmd(args[1:], stdout)
	case "fixtures":
		err = fixturesCmd(args[1:], stdout)
	case "origin":
		err = originCmd(args[1:])
	case "run":
		err = runCmd(args[1:], stdout, stderr)
	case "verify":
		err = verifyCmd(args[1:], stdout)
	case "summarize":
		err = summarizeCmd(args[1:], stdout)
	case "calibrate":
		err = calibrateCmd(args[1:], stdout)
	default:
		err = fmt.Errorf("unknown subcommand %q", args[0])
	}
	if err != nil {
		fmt.Fprintln(stderr, "inspection-assessment:", err)
		return 1
	}
	return 0
}

func planCmd(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("plan", flag.ContinueOnError)
	check := fs.String("check", "", "fail unless this file equals the generated plan")
	if err := fs.Parse(args); err != nil {
		return err
	}
	b := PlanJSON()
	if *check == "" {
		_, err := stdout.Write(b)
		return err
	}
	got, err := os.ReadFile(*check)
	if err != nil {
		return err
	}
	if !bytes.Equal(got, b) {
		return fmt.Errorf("%s is not the frozen plan generated by this harness (plan sha256 %s); regenerate it with `plan` only as a reviewed plan change", *check, sha256Hex(b))
	}
	fmt.Fprintf(stdout, "plan %s matches (sha256 %s)\n", PlanVersion, sha256Hex(b))
	return nil
}

// StaticPage is the /static/page.html fixture.
func StaticPage() []byte { return Filler(256<<10, "") }

func fixturesCmd(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("fixtures", flag.ContinueOnError)
	out := fs.String("out", "", "directory to write www/static/page.html into")
	guest := fs.String("guest", "", "built inspect-load.wasm to identify")
	src := fs.String("guest-source", "", "inspect-load source directory to identify")
	if err := fs.Parse(args); err != nil {
		return err
	}
	page := StaticPage()
	if *out != "" {
		if err := os.MkdirAll(filepath.Join(*out, "www", "static"), 0o755); err != nil { //nolint:gosec // fixture directory
			return err
		}
		if err := os.WriteFile(filepath.Join(*out, "www", "static", "page.html"), page, 0o644); err != nil { //nolint:gosec // fixture
			return err
		}
	}
	fmt.Fprintf(stdout, "static-page sha256 %s\n", sha256Hex(page))
	if *guest != "" {
		s, err := fileSHA(*guest)
		if err != nil {
			return err
		}
		fmt.Fprintf(stdout, "guest sha256 %s\n", s)
	}
	if *src != "" {
		s, err := TreeSHA(*src)
		if err != nil {
			return err
		}
		fmt.Fprintf(stdout, "guest-source tree sha256 %s\n", s)
	}
	return nil
}

func originCmd(args []string) error {
	fs := flag.NewFlagSet("origin", flag.ContinueOnError)
	listen := fs.String("listen", "127.0.0.1:19001", "loopback listen address")
	fault := fs.String("fault", "", "controlled fault: truncate | corrupt | stall")
	if err := fs.Parse(args); err != nil {
		return err
	}
	switch *fault {
	case "", "truncate", "corrupt", "stall":
	default:
		return fmt.Errorf("unknown fault %q", *fault)
	}
	srv := &http.Server{Addr: *listen, Handler: &Origin{Fault: *fault}, ReadHeaderTimeout: 10 * time.Second}
	return srv.ListenAndServe()
}

type multiFlag []string

func (m *multiFlag) String() string     { return strings.Join(*m, ",") }
func (m *multiFlag) Set(s string) error { *m = append(*m, s); return nil }

func runCmd(args []string, stdout, stderr io.Writer) error {
	fs := flag.NewFlagSet("run", flag.ContinueOnError)
	var targets multiFlag
	fs.Var(&targets, "target", "label:adapter:path of a Jul binary (repeatable; repetitions interleave targets)")
	out := fs.String("out", "", "new run directory (must not exist)")
	profile := fs.String("profile", "quick", "quick | qualification")
	suite := fs.String("suite", "", "named scenario suite")
	scenarios := fs.String("scenario", "", "comma-separated scenario ids")
	variants := fs.String("variants", "", "comma-separated subset of none,waf,wasm,both")
	reps := fs.Int("reps", 0, "repetitions per cell (default: the scenario's planned count; only the quick profile may lower it)")
	envelope := fs.String("envelope", "required", "required | none (none is only for smoke and unit use)")
	julCPUs := fs.String("jul-cpus", DefaultEnvelope.CPUs, "CPUs Jul is pinned to inside the envelope")
	originCPUs := fs.String("origin-cpus", "2,3", "CPUs the origin is pinned to (outside the envelope)")
	guest := fs.String("guest", "", "inspect-load.wasm (required for wasm/both variants)")
	guestSrc := fs.String("guest-source", "", "inspect-load source directory, for provenance")
	cert := fs.String("cert", "testdata/tls/localhost.crt", "TLS certificate")
	key := fs.String("key", "testdata/tls/localhost.key", "TLS key")
	fault := fs.String("fault", "", "controlled runner validation: origin fault truncate | corrupt | stall")
	killAfter := fs.Duration("kill-jul-after", 0, "controlled runner validation: SIGKILL Jul after this long in each cell")
	watchdog := fs.Duration("watchdog", 0, "per-cell limit (default: planned duration + 3m)")
	startup := fs.Duration("startup-timeout", 30*time.Second, "bounded Jul startup wait")
	if err := fs.Parse(args); err != nil {
		return err
	}
	if *out == "" || len(targets) == 0 {
		return errors.New("-out and at least one -target are required")
	}
	if _, err := os.Stat(*out); err == nil {
		return fmt.Errorf("%s exists; runs are never overwritten or resumed in place", *out)
	}
	prof, ok := Profiles[*profile]
	if !ok {
		return fmt.Errorf("unknown profile %q", *profile)
	}
	env := DefaultEnvelope
	env.CPUs = *julCPUs
	switch *envelope {
	case "required":
		if err := EnvelopeSupported(hostSys); err != nil {
			return fmt.Errorf("required envelope unsupported on this host; refusing to run unconstrained: %w", err)
		}
	case "none":
		if prof.AcceptanceEligible {
			return errors.New("the qualification profile requires -envelope required")
		}
		env = Envelope{Mode: "none", GOMAXPROCS: DefaultEnvelope.GOMAXPROCS}
	default:
		return fmt.Errorf("unknown envelope mode %q", *envelope)
	}
	cells, err := Select(*profile, *suite, *scenarios, *variants)
	if err != nil {
		return err
	}
	var specs []TargetSpec
	for _, t := range targets {
		s, err := ParseTarget(t)
		if err != nil {
			return err
		}
		if s.Path, err = filepath.Abs(s.Path); err != nil {
			return err
		}
		specs = append(specs, s)
	}
	needGuest := false
	for _, c := range cells {
		if _, wasm := VariantFlags(c.Variant); wasm {
			needGuest = true
		}
	}
	if needGuest && *guest == "" {
		return errors.New("-guest is required for wasm/both variants")
	}
	self, err := os.Executable()
	if err != nil {
		return err
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	opt := RunOptions{Out: *out, Profile: *profile, Fault: *fault, Targets: specs, Cells: cells, Reps: *reps, Env: env,
		OriginCPUs: *originCPUs, KillJulAfter: *killAfter, Watchdog: *watchdog, Startup: *startup, SampleEvery: 500 * time.Millisecond,
		Sys: hostSys, Self: self}
	for _, p := range []*string{guest, cert, key} {
		if *p != "" {
			if *p, err = filepath.Abs(*p); err != nil {
				return err
			}
		}
	}
	opt.Guest, opt.Cert, opt.Key = *guest, *cert, *key
	m, err := Execute(ctx, opt, *guestSrc, stderr)
	if err != nil {
		return err
	}
	fmt.Fprintf(stdout, "run %s: %s, %d results in %s\n", m.RunID, m.State, len(m.Results), *out)
	if m.State != "complete" {
		return fmt.Errorf("run %s ended %s: %s", m.RunID, m.State, m.Failure)
	}
	return nil
}

// Execute performs a run set and always finalises the manifest and sums.
func Execute(ctx context.Context, opt RunOptions, guestSrc string, log io.Writer) (Manifest, error) {
	if err := os.MkdirAll(opt.Out, 0o755); err != nil { //nolint:gosec // evidence directory
		return Manifest{}, err
	}
	fixtures, err := os.MkdirTemp("", "jul-inspection-fixtures-")
	if err != nil {
		return Manifest{}, err
	}
	defer func() { _ = os.RemoveAll(fixtures) }()
	opt.WWW = filepath.Join(fixtures, "www")
	if err := os.MkdirAll(opt.WWW, 0o700); err != nil {
		return Manifest{}, err
	}
	page := StaticPage()
	if err := os.MkdirAll(filepath.Join(opt.WWW, "static"), 0o700); err != nil {
		return Manifest{}, err
	}
	if err := os.WriteFile(filepath.Join(opt.WWW, "static", "page.html"), page, 0o600); err != nil {
		return Manifest{}, err
	}
	plan := PlanJSON()
	if err := os.WriteFile(filepath.Join(opt.Out, "plan.json"), plan, 0o644); err != nil { //nolint:gosec // evidence
		return Manifest{}, err
	}
	rules, _ := indentJSON(Rules)
	m := Manifest{Schema: ManifestSchema, RunID: filepath.Base(opt.Out), Started: time.Now().UTC(), State: "running",
		PlanVersion: PlanVersion, PlanSHA: sha256Hex(plan), RulesSHA: sha256Hex(rules), Profile: Profiles[opt.Profile],
		ScenarioSHAs: map[string]string{}, Harness: IdentifyBinary(opt.Self), Fault: opt.Fault,
		StaticPage: Artifact{Path: "generated: Filler(256 KiB)", SHA256: sha256Hex(page)}, Platform: HostPlatform(opt.Sys), Envelope: opt.Env,
		Placement: map[string]string{"jul": opt.Env.CPUs, "origin": opt.OriginCPUs, "client": opt.Sys.status(os.Getpid())["Cpus_allowed_list"]}}
	if opt.KillJulAfter > 0 {
		m.KillJulAfter = opt.KillJulAfter.String()
	}
	if opt.Env.Mode != "required" {
		m.Placement["jul"] = "unconstrained (envelope none)"
	}
	if s, err := fileSHA(opt.Cert); err == nil {
		m.TLS = Artifact{Path: opt.Cert, SHA256: s}
	}
	if opt.Guest != "" {
		g := Artifact{Path: opt.Guest, Source: guestSrc}
		g.SHA256, _ = fileSHA(opt.Guest)
		if guestSrc != "" {
			g.SourceSHA, _ = TreeSHA(guestSrc)
		}
		m.Guest = &g
	}
	for _, c := range opt.Cells {
		m.Selection = append(m.Selection, c.Scenario.ID+"/"+c.Variant)
		m.ScenarioSHAs[c.Scenario.ID+"/"+c.Variant] = ScenarioHash(c.Scenario)
		m.Repetitions = max(m.Repetitions, repsFor(opt, c.Scenario))
	}
	for _, t := range opt.Targets {
		m.Targets = append(m.Targets, TargetIdentity{TargetSpec: t, Binary: IdentifyBinary(t.Path), Adapter: Adapters[t.Adapter]})
	}
	finish := func(state, failure string) (Manifest, error) {
		now := time.Now().UTC()
		m.Ended, m.State, m.Failure = &now, state, failure
		if err := writeJSON(filepath.Join(opt.Out, "manifest.json"), m); err != nil {
			return m, err
		}
		return m, WriteSums(opt.Out)
	}
	if err := writeJSON(filepath.Join(opt.Out, "manifest.json"), m); err != nil {
		return m, err
	}
	origin, addr, err := StartOrigin(opt.Self, opt.OriginCPUs, opt.Fault)
	if err != nil {
		return finish("failed", "origin: "+err.Error())
	}
	defer func() {
		_ = origin.Process.Signal(syscall.SIGTERM)
		_ = origin.Wait()
	}()
	keyDir, err := os.MkdirTemp("", "jul-inspection-keys-")
	if err != nil {
		return finish("failed", err.Error())
	}
	defer func() { _ = os.RemoveAll(keyDir) }()
	r := &Runner{Opt: opt, Origin: addr, keys: map[string]string{}, keyDir: keyDir}
	maxReps := m.Repetitions
	for rep := 1; rep <= maxReps; rep++ {
		for _, c := range opt.Cells {
			if rep > repsFor(opt, c.Scenario) {
				continue
			}
			for _, t := range opt.Targets {
				if ctx.Err() != nil {
					m.Interrupted = true
					return finish("interrupted", "interrupted by signal")
				}
				res := r.RunCell(ctx, c, t, rep)
				rel, _ := filepath.Rel(opt.Out, filepath.Join(r.cellDir(c, t, rep), "result.json"))
				m.Results = append(m.Results, filepath.ToSlash(rel))
				fmt.Fprintf(log, "%s %s/%s/%s rep%d: state=%s valid=%v correct=%v %s\n", time.Now().UTC().Format(time.RFC3339), c.Scenario.ID, c.Variant, t.Label, rep,
					res.State, res.Valid, res.Correct, oneLine(res))
				if err := writeJSON(filepath.Join(opt.Out, "manifest.json"), m); err != nil {
					return m, err
				}
			}
		}
	}
	if ctx.Err() != nil {
		m.Interrupted = true
		return finish("interrupted", "interrupted by signal")
	}
	return finish("complete", "")
}

// repsFor returns a cell's repetitions. Outside the never-acceptance quick
// profile -reps may only raise the planned count.
func repsFor(opt RunOptions, sc Scenario) int {
	if opt.Profile == "quick" && opt.Reps > 0 {
		return opt.Reps
	}
	return max(opt.Reps, sc.Reps)
}

func oneLine(r RunResult) string {
	var parts []string
	for _, ph := range r.Phases {
		for _, c := range ph.Classes {
			parts = append(parts, fmt.Sprintf("%s/%s=%.1frps(%d/%d)", ph.Name, c.Workload, c.GoodputRPS, c.Verified, c.Attempts))
		}
		if ph.CPUFraction != nil {
			parts = append(parts, fmt.Sprintf("cpu=%.2f", *ph.CPUFraction))
		}
	}
	for _, f := range r.F4 {
		parts = append(parts, fmt.Sprintf("%s/%s:upload=%s(%.1fs) sibling=%s(%.0fms) dials=%d", f.Proto, f.Mode, f.UploadClass, f.UploadSeconds, f.SiblingClass, f.SiblingMs, f.Dials))
	}
	if r.Failure != "" {
		parts = append(parts, "failure="+r.Failure)
	}
	if len(r.Invalid) > 0 {
		parts = append(parts, "invalid="+strings.Join(r.Invalid, "; "))
	}
	if len(r.Findings) > 0 {
		parts = append(parts, "findings="+strings.Join(r.Findings, "; "))
	}
	return strings.Join(parts, " ")
}

func verifyCmd(args []string, stdout io.Writer) error {
	if len(args) == 0 {
		return errors.New("usage: verify RUN_DIR...")
	}
	for _, d := range args {
		if err := VerifyRun(d); err != nil {
			return fmt.Errorf("%s: %w", d, err)
		}
		fmt.Fprintf(stdout, "%s: verified\n", d)
	}
	return nil
}

func summarizeCmd(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("summarize", flag.ContinueOnError)
	out := fs.String("out", "", "directory for summary.md and summary.json (default: stdout markdown)")
	var pairs multiFlag
	fs.Var(&pairs, "compare", "baseline:candidate target labels (repeatable)")
	if err := fs.Parse(args); err != nil {
		return err
	}
	runs, err := LoadRuns(fs.Args())
	if err != nil {
		return err
	}
	var ps [][2]string
	for _, p := range pairs {
		a, b, ok := strings.Cut(p, ":")
		if !ok {
			return fmt.Errorf("-compare %q: want baseline:candidate", p)
		}
		ps = append(ps, [2]string{a, b})
	}
	s := BuildSummary(runs, ps)
	if *out == "" {
		_, err := io.WriteString(stdout, s.Markdown())
		return err
	}
	if err := os.MkdirAll(*out, 0o755); err != nil { //nolint:gosec // report directory
		return err
	}
	if err := os.WriteFile(filepath.Join(*out, "summary.md"), []byte(s.Markdown()), 0o644); err != nil { //nolint:gosec // report
		return err
	}
	return os.WriteFile(filepath.Join(*out, "summary.json"), s.JSON(), 0o644) //nolint:gosec // report
}

func calibrateCmd(args []string, stdout io.Writer) error {
	fs := flag.NewFlagSet("calibrate", flag.ContinueOnError)
	target := fs.String("target", "", "target label whose calibration runs decide the concurrency")
	if err := fs.Parse(args); err != nil {
		return err
	}
	runs, err := LoadRuns(fs.Args())
	if err != nil {
		return err
	}
	cal := Calibrate(runs, *target)
	if len(cal) == 0 {
		return fmt.Errorf("no calibration results for target %q", *target)
	}
	b, _ := indentJSON(cal)
	_, err = stdout.Write(b)
	return err
}
