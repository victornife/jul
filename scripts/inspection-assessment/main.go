// Command inspection-assessment is the maintained ADR 0032 (#700) inspection
// resource assessment harness: a synthetic origin, a verifying load client,
// F3/F4 probes, an owned and envelope-verified Jul process, run evidence with
// checksums, and deterministic summaries. See README.md.
