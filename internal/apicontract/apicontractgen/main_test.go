// TestCLIExitCodes pins the process contract: 0 on success, 1 on drift or an
// I/O failure, 2 on a usage error. `make generated-check` distinguishes them
// only by the exit code.
func TestCLIExitCodes(t *testing.T) {
	dir := t.TempDir()

	var stderr strings.Builder
	if code := cli([]string{"-out", dir}, &stderr); code != 0 {
		t.Fatalf("write mode exited %d: %s", code, stderr.String())
	}
	if _, err := os.Stat(artifactPath(dir)); err != nil {
		t.Fatalf("write mode produced no artifact: %v", err)
	}

	stderr.Reset()
	if code := cli([]string{"-out", dir, "-check"}, &stderr); code != 0 {
		t.Fatalf("check mode exited %d against fresh bytes: %s", code, stderr.String())
	}

	stderr.Reset()
	if err := os.WriteFile(artifactPath(dir), []byte("stale"), 0o644); err != nil {
		t.Fatalf("write stale: %v", err)
	}
	if code := cli([]string{"-out", dir, "-check"}, &stderr); code != 1 {
		t.Fatalf("check mode exited %d against a stale artifact, want 1", code)
	}
	if !strings.Contains(stderr.String(), apicontract.RegenerateCommand) {
		t.Fatalf("the failure did not reach stderr: %q", stderr.String())
	}

	stderr.Reset()
	if code := cli([]string{"-nonsense"}, &stderr); code != 2 {
		t.Fatalf("an unknown flag exited %d, want 2", code)
	}
	if stderr.Len() == 0 {
		t.Fatal("a usage error printed nothing")
	}
}

// TestCLIDefaultsToTheDocsDirectory documents the default an operator relies on
// when running the generator by hand from the repository root.
func TestCLIDefaultsToTheDocsDirectory(t *testing.T) {
	var stderr strings.Builder
	// Check mode against the real committed artifact: it must already be
	// current, which also proves the default -out value points at it.
	t.Chdir("../../..")
	if code := cli([]string{"-check"}, &stderr); code != 0 {
		t.Fatalf("check mode against the default output directory exited %d: %s", code, stderr.String())
	}
}
